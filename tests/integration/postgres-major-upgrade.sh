#!/usr/bin/env bash
# Real engine/storage test. Run only on a disposable Docker daemon.
set -Eeuo pipefail
[[ "${POSTGRES_UPGRADE_DISPOSABLE:-}" == true ]] || { echo 'Set POSTGRES_UPGRADE_DISPOSABLE=true on a disposable Docker daemon.' >&2; exit 2; }
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TEMP_ROOT="$(mktemp -d)"
export INSTALLER_GLOBAL_STATE_DIR="${TEMP_ROOT}/global"
source "${SCRIPT_DIR}/lib/common.sh"
source "${SCRIPT_DIR}/lib/configure.sh"
source "${SCRIPT_DIR}/lib/update.sh"
PROJECT_ROOT="${TEMP_ROOT}/project"
COMPOSE_PROJECT_NAME="pg18-test-$(date +%s)-${RANDOM}"
set_runtime_paths
mkdir -p "${STATE_DIR}/backups/database"
context_dir="${STATE_DIR}/.protected-update.test${RANDOM}"
mkdir -p "${context_dir}"
pg15='postgres@sha256:4006528dcbdd9be8c1aaa50389caea4e93c46d6f54c3533bcd3253725e526e23'
pg18='postgres@sha256:d8703cd7fba306b9fec9268ecedfa8a966846c053036a60e3635791957eb2f66'
project="${COMPOSE_PROJECT_NAME}"
cleanup() {
  # Exact project and its own recorded volumes only; never a parent-stack cleanup.
  docker ps -aq --filter "label=com.docker.compose.project=${project}" | xargs -r docker rm -f >/dev/null
  while IFS= read -r volume; do
    [[ "${volume}" == "${project}_postgres"* ]] || continue
    [[ "$(docker volume inspect --format '{{index .Labels "com.docker.compose.project"}}' "${volume}")" == "${project}" ]] || continue
    docker volume rm "${volume}" >/dev/null 2>&1 || true
  done < <(docker volume ls -q --filter "label=com.docker.compose.project=${project}")
  docker network rm "${project}_default" >/dev/null 2>&1 || true
  rm -rf "${TEMP_ROOT}"
}
trap cleanup EXIT
cat > "${STATE_FILE}" <<EOF
PROJECT_ROOT='${PROJECT_ROOT}'
COMPOSE_PROJECT_NAME='${project}'
POSTGRES_DB='fixture'
POSTGRES_USER='fixture'
POSTGRES_IMAGE='${pg15}'
REDIS_IMAGE='redis:7-alpine'
BOT_HTTP_PORT='18080'
EOF
printf '%s\n' 'POSTGRES_PASSWORD=disposable-fixture' > "${BOT_ENV_FILE}"
: > "${BOT_OVERRIDE_ENV_FILE}"
render_compose_file
compose_cmd up -d --wait --wait-timeout 180 postgres
compose_cmd exec -T postgres psql -X -v ON_ERROR_STOP=1 -U fixture -d fixture <<'SQL'
CREATE TABLE alembic_version(version_num text PRIMARY KEY);
INSERT INTO alembic_version VALUES ('0131');
CREATE TABLE users(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, balance bigint, label text);
INSERT INTO users(balance,label) VALUES (12345,'owner-like fixture'),(67890,'second fixture');
CREATE TABLE subscriptions(id bigserial PRIMARY KEY, user_id bigint REFERENCES users, expires_at timestamptz);
INSERT INTO subscriptions(user_id,expires_at) VALUES (1,'2027-01-15 12:34:56+00'),(2,'2027-02-16 12:34:56+00');
CREATE TABLE legacy_transactions(id bigserial PRIMARY KEY, user_id bigint REFERENCES users, amount bigint, external_id text);
INSERT INTO legacy_transactions(user_id,amount,external_id) VALUES (1,19900,'synthetic-legacy');
SELECT setval('users_id_seq', 97, false);
SQL
# The Docker daemon is outside this runner container; its disk cannot be stat'ed
# here. The native Ubuntu lifecycle gate exercises the actual host disk preflight.
postgres_require_upgrade_space() { :; }
prepare_postgres_update_storage "${context_dir}" "${pg18}"
PROTECTED_UPDATE_ADAPTER_SOURCE_ONLY=true
source "${SCRIPT_DIR}/lib/protected_update_adapter.sh"
write_context_value target-postgres-image "${pg18}"
dump="$(create_verified_update_dump pg18-test)"
write_context_value dump-reference "${dump}"
write_context_value dump-sha256 "$(file_sha256 "${dump}")"
write_context_value before-revision 0131
protect_postgres_upgrade
target_volume="$(context_value target-postgres-volume)"
[[ "${target_volume}" != "${project}_postgres_data" ]]
render_compose_file "${pg18}" redis:7-alpine 18 "${target_volume}"
apply_postgres_upgrade
mv "${STATE_FILE}" "${STATE_FILE}.fixture-lost"
printf 'compose_project=%s\n' "${project}" > "${PROJECT_ROOT}/.migration-resources-created"
recover_postgres_runtime_identity "${PROJECT_ROOT}"
[[ "${RECOVERED_POSTGRES_MAJOR}" == 18 && "${RECOVERED_POSTGRES_VOLUME}" == "${target_volume}" ]]
mv "${STATE_FILE}.fixture-lost" "${STATE_FILE}"
[[ "$(compose_cmd exec -T postgres psql -XAt -U fixture -d fixture -c 'SHOW server_version_num')" == 18* ]]
[[ "$(compose_cmd exec -T postgres psql -XAt -U fixture -d fixture -c "SELECT balance FROM users ORDER BY id")" == $'12345\n67890' ]]
[[ "$(compose_cmd exec -T postgres psql -XAt -U fixture -d fixture -c "SELECT external_id FROM legacy_transactions")" == synthetic-legacy ]]
[[ "$(compose_cmd exec -T postgres psql -XAt -U fixture -d fixture -c "SELECT amount FROM legacy_transactions")" == 19900 ]]
[[ "$(compose_cmd exec -T postgres psql -XAt -U fixture -d fixture -c "SELECT to_char(expires_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') FROM subscriptions ORDER BY id")" == $'2027-01-15 12:34:56\n2027-02-16 12:34:56' ]]
[[ "$(compose_cmd exec -T postgres psql -XAt -U fixture -d fixture -c "SELECT nextval(\$\$users_id_seq\$\$)")" == 97 ]]
if verify_postgres_upgrade_manifest changed-sequence; then
  echo 'Changed sequence state was accepted.' >&2
  exit 1
fi
docker volume inspect "${project}_postgres_data" >/dev/null
# Return to the untouched PG15 volume and compare the protected database manifest.
render_compose_file "${pg15}" redis:7-alpine 15 "${project}_postgres_data"
compose_cmd up -d --wait --wait-timeout 180 postgres
postgres_database_manifest > "${context_dir}/rollback-manifest.json"
cmp "${context_dir}/postgres-before.json" "${context_dir}/rollback-manifest.json"
# Simulate a killed process after creating PG18 but before restoring the dump.
context_dir="${STATE_DIR}/.protected-update.interrupted${RANDOM}"
mkdir -p "${context_dir}"
prepare_postgres_update_storage "${context_dir}" "${pg18}"
write_context_value target-postgres-image "${pg18}"
write_context_value dump-reference "${dump}"
write_context_value dump-sha256 "$(file_sha256 "${dump}")"
write_context_value before-revision 0131
protect_postgres_upgrade
interrupted_volume="$(context_value target-postgres-volume)"
render_compose_file "${pg18}" redis:7-alpine 18 "${interrupted_volume}"
compose_cmd up -d --no-deps --wait --wait-timeout 180 postgres
if apply_postgres_upgrade; then
  echo 'Interrupted nonempty target volume was silently reused.' >&2
  exit 1
fi
render_compose_file "${pg15}" redis:7-alpine 15 "${project}_postgres_data"
compose_cmd up -d --wait --wait-timeout 180 postgres
verify_postgres_upgrade_manifest interrupted-rollback
# A new operation gets a fresh volume; the interrupted volume remains intact.
context_dir="${STATE_DIR}/.protected-update.retry${RANDOM}"
mkdir -p "${context_dir}"
prepare_postgres_update_storage "${context_dir}" "${pg18}"
write_context_value target-postgres-image "${pg18}"
write_context_value dump-reference "${dump}"
write_context_value dump-sha256 "$(file_sha256 "${dump}")"
write_context_value before-revision 0131
protect_postgres_upgrade
retry_volume="$(context_value target-postgres-volume)"
[[ "${retry_volume}" != "${interrupted_volume}" ]]
render_compose_file "${pg18}" redis:7-alpine 18 "${retry_volume}"
apply_postgres_upgrade
docker volume inspect "${interrupted_volume}" >/dev/null
printf '%s\n' 'Real PG15 -> PG18 transfer, counter mismatch, interrupted target, rollback and retry passed.'
